import { AdaptationChannel, ExportTool, RetrofitRecipe, VehicleProfile } from '../types/mib3';

/**
 * Normalizes a hex coding string: removes spaces, colons, makes uppercase.
 */
export function normalizeHexString(hex: string): string {
  return hex.replace(/[^0-9A-Fa-f]/g, '').toUpperCase();
}

/**
 * Splits a continuous 64-char hex string into 32 byte chunks.
 */
export function hexStringToBytes(hex: string, length = 32): string[] {
  const clean = normalizeHexString(hex).padEnd(length * 2, '0');
  const bytes: string[] = [];
  for (let i = 0; i < length; i++) {
    const start = i * 2;
    bytes.push(clean.substring(start, start + 2) || '00');
  }
  return bytes;
}

/**
 * Joins an array of 2-char hex bytes into a continuous hex string.
 */
export function bytesToHexString(bytes: string[]): string {
  return bytes.map(b => b.padStart(2, '0').toUpperCase()).join('');
}

/**
 * Converts a hex byte (e.g. "1F") to an array of 8 boolean bits [bit0, bit1, ..., bit7].
 */
export function byteToBits(byteHex: string): boolean[] {
  const val = parseInt(byteHex, 16) || 0;
  const bits: boolean[] = [];
  for (let i = 0; i < 8; i++) {
    bits.push(((val >> i) & 1) === 1);
  }
  return bits;
}

/**
 * Converts an array of 8 boolean bits back into a 2-char hex string.
 */
export function bitsToByteHex(bits: boolean[]): string {
  let val = 0;
  for (let i = 0; i < 8; i++) {
    if (bits[i]) {
      val |= (1 << i);
    }
  }
  return val.toString(16).padStart(2, '0').toUpperCase();
}

/**
 * Toggles or sets a specific bit in a full coding hex string.
 */
export function setBitInCodingString(
  codingHex: string,
  byteIndex: number,
  bitIndex: number,
  newBitValue: boolean
): string {
  const bytes = hexStringToBytes(codingHex);
  if (byteIndex < 0 || byteIndex >= bytes.length) return codingHex;
  
  const bits = byteToBits(bytes[byteIndex]);
  bits[bitIndex] = newBitValue;
  bytes[byteIndex] = bitsToByteHex(bits);
  
  return bytesToHexString(bytes);
}

/**
 * Formats a hex string with spaces every 2 characters for easy reading.
 */
export function formatHexWithSpaces(hex: string): string {
  const clean = normalizeHexString(hex);
  return clean.match(/.{1,2}/g)?.join(' ') || hex;
}

/**
 * Generates ready-to-use diagnostic commands/scripts for various tools.
 */
export function generateToolExport(
  tool: ExportTool,
  profile: VehicleProfile,
  codingHex: string,
  stockCodingHex: string,
  changedChannels: AdaptationChannel[],
  appliedRecipes: RetrofitRecipe[]
): string {
  const formattedCoding = formatHexWithSpaces(codingHex);
  const formattedStock = formatHexWithSpaces(stockCodingHex);
  const dateStr = new Date().toISOString().replace('T', ' ').substring(0, 19);

  switch (tool) {
    case 'vcds':
      return `; ==============================================================================
; ROSS-TECH VCDS / VAG-COM CODING INSTRUCTIONS
; Generated by MIB3 VAG Coding Studio
; Vehicle: ${profile.name} (${profile.platform})
; VIN: ${profile.vinSample}
; Target ECU: 5F - Information Electronics 1 (MIB3)
; Timestamp: ${dateStr}
; ==============================================================================

[SECURITY ACCESS]
1. Connect HEX-NET / HEX-V2 cable to OBD2 port and turn ignition ON (Terminal 15).
2. Select [Control Module 5F - Information Electr.]
3. Select [Security Access - 16] -> Enter Code: 20103 -> Click [Do It!]
   *(Note: Ensure SFD is unlocked via Online/Token if prompted)*

[LONG CODING]
4. Select [Coding - 07] -> Long Coding Helper
   Original Coding: ${formattedStock}
   NEW MIB3 CODING: ${formattedCoding}
5. Click [Do It!] and verify "Coding Accepted" message.

[ADAPTATION CHANNELS]
6. Select [Adaptation - 10]
${changedChannels.map((ch, idx) => `   (${idx + 1}) Channel: [${ch.channelName}] -> Subchannel: [${ch.subName || 'N/A'}]
       Old Value: ${ch.defaultValue}
       NEW Value: ${ch.currentValue}
       Requires SFD: ${ch.requiresSfd ? 'YES' : 'NO'}`).join('\n')}

[RESET / REBOOT INFOTAINMENT]
7. Once coding is applied, execute soft reset:
   Hold MIB3 Power button for 15-20 seconds until the display screen restarts.
; ==============================================================================`;

    case 'obdeleven':
      return `/* ==============================================================================
 * OBDeleven PRO Procedure Guide
 * Vehicle: ${profile.name}
 * Firmware: ${profile.firmwareVersion}
 * Module: 5F (Multimedia / Information Control Unit)
 * ============================================================================== */

1. Open OBDeleven App -> Connect Bluetooth Dongle -> Turn Ignition ON.
2. If vehicle has SFD enabled:
   - Navigate to Module 5F -> SFD Protection -> Select "Unlock SFD (Automatically)"
   - Wait for "SFD Successfully Unlocked (Valid for 90 minutes)".

3. Navigate to: Module 5F -> Long Coding:
   - Byte String:
     ${formattedCoding}
   - Or modify individual bits:
${appliedRecipes.flatMap(r => r.byteChanges).map(bc => `     * Byte ${bc.byteIndex}, Bit ${bc.bitIndex} -> Set to ${bc.targetValue ? 'ON (1)' : 'OFF (0)'} (${bc.reason})`).join('\n') || '     * (Manual bit updates)'}
   - Hold Green Checkmark to write coding.

4. Navigate to: Module 5F -> Adaptations:
${changedChannels.map(ch => `   * Search for: "${ch.channelName}" -> "${ch.subName}"
     -> Change to: "${ch.currentValue}" -> Swipe to confirm.`).join('\n\n')}

5. Hard Reboot MIB3:
   Press and hold the volume/power knob until the welcome logo reappears.`;

    case 'odis':
      return `<?xml version="1.0" encoding="UTF-8"?>
<!-- ========================================================================== -->
<!-- ODIS-Engineering (ODIS-E) Automation Macro Script                           -->
<!-- Target ECU: 005F (Information Electronics 1 - MIB3)                       -->
<!-- Vehicle: ${profile.name} | Chassis: ${profile.platform}                   -->
<!-- ========================================================================== -->
<OdisEngineeringMacro version="2.4" generator="MIB3-Coding-Studio">
  <SessionHeader>
    <EcuAddress>0x5F</EcuAddress>
    <DiagnosticServiceSession>0x03</DiagnosticServiceSession>
    <SecurityAccessCode>20103</SecurityAccessCode>
    <TargetVin>${profile.vinSample}</TargetVin>
  </SessionHeader>

  <DiagnosticSteps>
    <!-- Step 1: Open Diagnostic Session Extended 0x03 -->
    <Step order="1" service="0x10" subfunction="0x03" name="ExtendedDiagnosticSession" />

    <!-- Step 2: Security Access Login -->
    <Step order="2" service="0x27" subfunction="0x01" name="SecurityAccessSeedRequest" />
    <Step order="3" service="0x27" subfunction="0x02" key="20103" name="SecurityAccessSendKey" />

    <!-- Step 3: Write Long Coding 0x2E 0x0600 -->
    <Step order="4" service="0x2E" identifier="0x0600" name="WriteDataByIdentifier_LongCoding">
      <PayloadHex>${normalizeHexString(codingHex)}</PayloadHex>
    </Step>

    <!-- Step 4: Write Staged Adaptations -->
${changedChannels.map((ch, idx) => `    <Step order="${5 + idx}" service="0x2E" channel="${ch.channelName}" sub="${ch.subName}">
      <Param name="target_value">${ch.currentValue}</Param>
    </Step>`).join('\n')}

    <!-- Step 5: Soft ECU Reset -->
    <Step order="${5 + changedChannels.length}" service="0x11" subfunction="0x01" name="EcuHardReset" />
  </DiagnosticSteps>
</OdisEngineeringMacro>`;

    case 'autel_jvci':
      return `; ==============================================================================
; AUTEL MAXIFLASH JVCI / J2534 PASSTHRU (AUTEL MAXIIM IM608 PRO / IM608 II)
; Target ECU: Module 5F (Information Electronics 1 - MIB3)
; Vehicle: ${profile.name} | VIN: ${profile.vinSample}
; Firmware: ${profile.firmwareVersion}
; ==============================================================================

[METHOD 1: USING AUTEL MAXIIM IM608 / IM608 PRO TABLET]
1. Connect Autel MaxiFlash JVCI VCI to OBD2 port and connect to IM608 via USB or Bluetooth.
2. Ensure battery maintainer is connected to vehicle (> 12.5V).
3. Select [Diagnostics] -> [Volkswagen / Audi / SEAT / Skoda] -> [Automatic Selection] (Reads VIN: ${profile.vinSample}).
4. Select [Control Unit] -> [5F Information Control Unit 1]
5. (SFD UNLOCK): If prompted with "SFD Security Gateway Protected", select [Online Security Access] / [Unlock SFD].
6. Select [Security Access] -> Enter Code: 20103 -> Confirm.
7. Select [Coding] -> [Manual Long Coding]:
   Input New 32-Byte String:
   ${formattedCoding}
   Click [Write Coding] and verify "Coding Succeeded".
8. Select [Adaptation]:
${changedChannels.map((ch, idx) => `   (${idx + 1}) Search: [${ch.channelName}] -> Channel: [${ch.subName || 'N/A'}]
       Set to: ${ch.currentValue}`).join('\n')}
9. Perform Soft Reset: Hold MIB3 volume knob for 15s until system restarts.

[METHOD 2: USING AUTEL MAXIFLASH JVCI AS J2534 ON PC (ODIS-E / PYTHON PASSTHRU)]
J2534 Device: Autel MaxiFlash JVCI (DLL: MaxiFlash.dll / AUTEL_J2534.dll)
Registry Key: HKLM\\Software\\PassThruSupport.04.04\\Autel MaxiFlash JVCI

Python / C J2534 Configuration:
- Protocol: ISO15765 (0x06) | Baud Rate: 500000 | Flags: 0x00
- Tx ID: 0x00000714 | Rx Flow Control: Filter 0x0000077E, Mask 0x000007FF
- UDS Request Sequence:
  TX: 10 03               (Extended Session)
  TX: 27 01               (Seed Request)
  TX: 27 02 [Token]       (Send Security Key 20103)
  TX: 2E 06 00 ${normalizeHexString(codingHex)}
  TX: 11 01               (Hard Reset)`;

    case 'vcp':
      return `// VCP (Vag Can Pro) Execution Script
// MIB3 Module 5F Automation
// Vehicle: ${profile.name}

CONNECT 0x5F
DIAGSESSION 0x03
SECACCESS 20103
WRITECODING ${normalizeHexString(codingHex)}

${changedChannels.map(ch => `WRITEADAPT "${ch.channelName}" "${ch.subName}" "${ch.currentValue}"`).join('\n')}

ECURESET 0x01
DISCONNECT`;

    case 'doip_raw':
      return `#!/usr/bin/env bash
# ==============================================================================
# ISO 14229 / UDS over DoIP (Ethernet Diagnostic Script) for MIB3
# Target: 192.168.1.4 (MIB3 Internal Interface) | Port: 13400 (DoIP)
# ECU Target Address: 0x105F (DoIP Logical Address for 5F)
# ==============================================================================

set -e
DOIP_HOST="192.168.1.4"
DOIP_PORT="13400"
LOGICAL_5F="105F"

echo "[*] Initializing DoIP Routing Activation to 5F..."
# DoIP Header: 0x02 0xFD (DoIP version 2), Type 0x0005 (Routing Activation Request)
# Send routing activation and connect...

echo "[*] Requesting Extended Diagnostic Session (0x10 0x03)..."
# Raw UDS: 10 03

echo "[*] Sending Security Access (20103)..."
# Raw UDS: 27 01 -> calculate key -> 27 02 ...

echo "[*] Writing 32-Byte Long Coding via UDS 0x2E 0x0600..."
CODING_HEX="${normalizeHexString(codingHex)}"
echo "Payload: 2E 06 00 $CODING_HEX"

echo "[*] Writing Adaptations..."
${changedChannels.map(ch => `# Channel: ${ch.channelName} -> ${ch.subName} = ${ch.currentValue}`).join('\n')}

echo "[*] Sending ECU Reset (0x11 0x01)..."
echo "[+] Coding deployment complete! Rebooting MIB3 headunit..."`;
  }
}
